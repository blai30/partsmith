/** The repository a root crate names, which the OCCT statement needs. */
function requiredRepository(repository, rootName) {
  if (!repository) {
    throw new Error(
      `${rootName} names no repository in its Cargo.toml, which the OCCT statement needs (docs/spec/delivery.md section 2.9).`,
    )
  }
  return repository
}

/** `entries` marked as part of the desktop app on every platform. */
function onEveryPlatform(entries) {
  return entries.map((listed) => ({ ...listed, platforms: EVERY_PLATFORM }))
}

/** Both texts as `{ desktop, web }`, read from the repository at `root`, with every command sent through `run`. */
export async function generateNotices(root, { run }) {
  const pins = await readPins(root)
  const partsmith = await normalizedFile(join(root, 'LICENSE'))
  const occt = await occtEntries(root, pins)
  const fonts = await fontEntries(root)
  const rust = await rustEntry(root, pins, partsmith)
  const emscripten = await emscriptenEntries(root, pins)
  const graphs = await crateGraphs(root, run)
  const packages = await npmPackages(root, run)

  const crateKeys = new Set(graphs.desktop.map(keyOf))
  const crates = [...graphs.desktop, ...graphs.web.filter((crate) => !crateKeys.has(keyOf(crate)))]
  const crateTexts = await textsByKey(root, crates, true)
  const npmTexts = await textsByKey(root, packages, false)
  const crateEntry = (crate, platforms) =>
    packageEntry(
      crate,
      crateTexts,
      `https://crates.io/crates/${crate.name}/${crate.version}`,
      platforms,
    )
  const npmEntry = (listed) =>
    packageEntry(
      listed,
      npmTexts,
      `https://www.npmjs.com/package/${listed.name}/v/${listed.version}`,
      null,
    )
  const webView2 = await webView2Entries(root, graphs.desktop)

  const desktop = renderNotices({
    heading: DESKTOP_NOTICES_HEADING,
    scope: 'The Partsmith desktop app for Linux, Windows and macOS',
    partsmith,
    occt: {
      statement: desktopStatement(
        pins,
        requiredRepository(graphs.desktopRepository, DESKTOP_ROOT_CRATE),
      ),
      entries: onEveryPlatform(occt),
    },
    fonts: onEveryPlatform(fonts),
    crates: graphs.desktop.map((crate) => crateEntry(crate, crate.platforms)),
    packages: onEveryPlatform(packages.map(npmEntry)),
    libraries: [...onEveryPlatform([rust]), ...webView2],
  })
  const web = renderNotices({
    heading: WEB_NOTICES_HEADING,
    scope: 'The Partsmith web app',
    partsmith,
    occt: {
      statement: webStatement(pins, requiredRepository(graphs.webRepository, WEB_ROOT_CRATE)),
      entries: occt,
    },
    fonts,
    crates: graphs.web.map((crate) => crateEntry(crate, null)),
    packages: packages.map(npmEntry),
    libraries: [rust, ...emscripten],
  })
  return { desktop, web }
}

/** The bytes of the file at `path`, or null when it does not exist. */
async function bytesOrNull(path) {
  try {
    return await readFile(path)
  } catch (error) {
    if (isMissing(error)) {
      return null
    }
    throw error
  }
}

/** Runs the command with its arguments and returns its exit status. */
async function main(commandArguments) {
  const [command] = commandArguments
  if (commandArguments.length !== 1 || !['write', 'check'].includes(command)) {
    process.stderr.write(`${USAGE}\n`)
    return 2
  }
  try {
    const { desktop, web } = await generateNotices(repositoryRoot, { run: runCommand })
    const files = [
      [DESKTOP_FILE, desktop],
      [WEB_FILE, web],
    ]
    if (command === 'write') {
      await Promise.all(files.map(([path, text]) => writeFile(join(repositoryRoot, path), text)))
      process.stdout.write(`Wrote ${DESKTOP_FILE} and ${WEB_FILE}.\n`)
      return 0
    }
    const committed = await Promise.all(
      files.map(([path]) => bytesOrNull(join(repositoryRoot, path))),
    )
    const outdated = files.filter(
      ([, text], i) => committed[i] === null || !committed[i].equals(Buffer.from(text, 'utf8')),
    )
    if (outdated.length > 0) {
      process.stderr.write(
        outdated.map(([path]) => `${path} is out of date. Run: pnpm -C ui notices\n`).join(''),
      )
      return 1
    }
    process.stdout.write(`${DESKTOP_FILE} and ${WEB_FILE} are up to date.\n`)
    return 0
  } catch (error) {
    process.stderr.write(`${error.message}\n`)
    return 1
  }
}

// Runs as a command only when Node started this file, not when another module imports it.
const startedFile = process.argv[1]
if (startedFile !== undefined && (await realpath(startedFile)) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2))
}
