/** Runs a command through `run`, turning a failure into the message of section 4. */
async function checkedRun(run, command, commandArguments, directory) {
  try {
    return await run(command, commandArguments, directory)
  } catch (error) {
    throw new Error(commandFailureMessage(command, commandArguments, error), { cause: error })
  }
}

/** The parsed `cargo metadata` of `root` for `triple` (input 1). */
async function cargoMetadata(root, run, triple) {
  const commandArguments = [
    'metadata',
    '--format-version',
    '1',
    '--locked',
    '--all-features',
    '--filter-platform',
    triple,
  ]
  return JSON.parse(await checkedRun(run, 'cargo', commandArguments, root))
}

/** The key of a package or crate: its name and version. */
function keyOf(listed) {
  return `${listed.name} ${listed.version}`
}

/**
 * The crates of the desktop app and of the web app with the repository each root crate names. Desktop crates are the
 * union over DESKTOP_TARGETS, each with the platforms whose graph holds it.
 */
async function crateGraphs(root, run) {
  const triples = [...DESKTOP_TARGETS.map((target) => target.triple), WEB_TRIPLE]
  const graphs = await readInOrder(triples, (triple) => cargoMetadata(root, run, triple))
  const webMetadata = graphs.pop()
  const desktop = new Map()
  DESKTOP_TARGETS.forEach(({ platform }, i) => {
    for (const crate of artifactCrates(graphs[i], DESKTOP_ROOT_CRATE)) {
      const known = desktop.get(keyOf(crate)) ?? { ...crate, platforms: [] }
      known.platforms.push(platform)
      desktop.set(keyOf(crate), known)
    }
  })
  return {
    desktop: [...desktop.values()].toSorted(compareNameAndVersion),
    desktopRepository: workspacePackage(graphs[0], DESKTOP_ROOT_CRATE).repository,
    web: artifactCrates(webMetadata, WEB_ROOT_CRATE),
    webRepository: workspacePackage(webMetadata, WEB_ROOT_CRATE).repository,
  }
}

/** The npm packages that ship (input 2) as `{ name, version, license, licenseFile, folder }`. */
async function npmPackages(root, run) {
  const uiFolder = join(root, 'ui')
  const listing = (commandArguments) =>
    checkedRun(run, 'pnpm', ['licenses', 'list', ...commandArguments], uiFolder)
  const [production, all] = await readInOrder([['--prod', '--json'], ['--json']], listing)
  const packages = shippedPackages(production, all)
  return packages.map(({ name, version, license, path }) => ({
    name,
    version,
    license,
    licenseFile: null,
    folder: path,
  }))
}

/** The regular files directly in `folder`, as full paths in byte order of names; none when it does not exist. */
async function regularFilesIn(folder) {
  try {
    const entries = await readdir(folder, { withFileTypes: true })
    return entries
      .filter((listed) => listed.isFile())
      .map((listed) => listed.name)
      .toSorted(compareText)
      .map((name) => join(folder, name))
  } catch (error) {
    if (isMissing(error)) {
      return []
    }
    throw error
  }
}

/**
 * The texts of a package without license files (input 3): the standard text that its expression allows alone, or
 * the committed copies from its repository.
 */
async function fallbackTexts(root, listed) {
  const identifier = STANDARD_LICENSES.find(
    (candidate) => listed.license !== null && licenseAllowed(listed.license, [candidate]),
  )
  if (identifier !== undefined) {
    const path = `licenses/${identifier}.txt`
    try {
      return {
        textSource: 'standard',
        texts: [await normalizedFile(join(root, COPIES_FOLDER, path))],
      }
    } catch (error) {
      if (isMissing(error)) {
        throw new Error(
          `${keyOf(listed)} ships no license text, and ${COPIES_FOLDER}/${path} is missing. Add the SPDX License List text of ${identifier} there.`,
          { cause: error },
        )
      }
      throw error
    }
  }
  const copies = await regularFilesIn(join(root, COPIES_FOLDER, 'crates', listed.name))
  const texts = distinctTexts(await Promise.all(copies.map(normalizedFile)))
  if (texts.length === 0) {
    throw new Error(
      `${keyOf(listed)} ships no license text, and ${COPIES_FOLDER}/crates/${listed.name}/ is missing. Commit a copy of the license file of its repository there (docs/spec/delivery.md section 2.9).`,
    )
  }
  return { textSource: 'repository', texts }
}

/** The license texts of a crate or npm package as `{ textSource, texts }`, checking a crate's prebuilt libraries. */
async function packageTexts(root, listed, isCrate) {
  const paths = await folderListing(listed.folder)
  if (isCrate) {
    const [library] = prebuiltLibrariesOf(paths)
    if (
      library !== undefined &&
      !PREBUILT_LIBRARY_CRATES.some(({ crate }) => crate === listed.name)
    ) {
      throw new Error(
        `${keyOf(listed)} ships the prebuilt library ${library}. Find its license, give it an entry if it needs one, and add the crate to PREBUILT_LIBRARY_CRATES (docs/spec/delivery.md section 2.9).`,
      )
    }
  }
  const excluded = isCrate
    ? EXCLUDED_LICENSE_FILES.filter(({ crate }) => crate === listed.name).map(({ path }) => path)
    : []
  const files = licenseFilesOf(paths, listed.licenseFile, excluded)
  const texts = distinctTexts(
    await Promise.all(files.map((path) => normalizedFile(join(listed.folder, path)))),
  )
  return texts.length > 0 ? { textSource: 'shipped', texts } : fallbackTexts(root, listed)
}

/** The texts of every package of `packages` by key; the first failure in their order is the one reported. */
async function textsByKey(root, packages, isCrate) {
  const texts = await readInOrder(packages, (listed) => packageTexts(root, listed, isCrate))
  return new Map(packages.map((listed, i) => [keyOf(listed), texts[i]]))
}

/** The entry of a crate or npm package with its texts, on `platforms` (null in the web file). */
function packageEntry(listed, texts, url, platforms) {
  return noticesEntry({
    name: listed.name,
    version: listed.version,
    license: listed.license,
    url,
    platforms,
    ...texts.get(keyOf(listed)),
  })
}

