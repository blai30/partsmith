/** Orders two strings by code units, which is byte order for the ASCII paths and names here. */
function compareText(first, second) {
  if (first === second) {
    return 0
  }
  return first < second ? -1 : 1
}

/** `text` normalized as below; '' when nothing is left. */
export function normalizeText(text) {
  const lines = text
    .replace(/^\uFEFF/, '')
    .replaceAll(/\r\n?/g, '\n')
    .replaceAll('\f', '')
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/, ''))
  const first = lines.findIndex((line) => line !== '')
  if (first === -1) {
    return ''
  }
  const last = lines.findLastIndex((line) => line !== '')
  return `${lines.slice(first, last + 1).join('\n')}\n`
}

/** The normalized text of the file at `path`, decoded as UTF-8 with U+FFFD for each invalid byte sequence. */
async function normalizedFile(path) {
  return normalizeText((await readFile(path)).toString('utf8'))
}

/** Whether `error` says that a file does not exist or is not a file. */
function isMissing(error) {
  return ['ENOENT', 'ENOTDIR', 'EISDIR'].includes(error.code)
}

/** The section 4 message for a committed copy that inputs 4 or 6 name and that is missing. */
function missingCopyMessage(path) {
  return `${COPIES_FOLDER}/${path} is missing. Make it as docs/spec/delivery.md section 2.9 describes, from the version that the pins name.`
}

/** The text of the committed copy `path` under ui/scripts/notices/ of `root`, or the missing-copy message. */
async function committedCopy(root, path) {
  try {
    return (await readFile(join(root, COPIES_FOLDER, path))).toString('utf8')
  } catch (error) {
    if (isMissing(error)) {
      throw new Error(missingCopyMessage(path), { cause: error })
    }
    throw error
  }
}

/** The normalized text of the committed copy `path` under ui/scripts/notices/ of `root`. */
async function normalizedCopy(root, path) {
  return normalizeText(await committedCopy(root, path))
}

/** Every regular file below `directory` as a path starting with `prefix`; symbolic links are not followed. */
async function regularFilesBelow(directory, prefix) {
  const children = await readdir(directory, { withFileTypes: true })
  const nested = await Promise.all(
    children.map((child) => {
      if (child.isDirectory()) {
        return regularFilesBelow(join(directory, child.name), `${prefix}${child.name}/`)
      }
      return child.isFile() ? [`${prefix}${child.name}`] : []
    }),
  )
  return nested.flat()
}

/** Every regular file below `folder`, without following symbolic links, relative to it with `/`, in byte order. */
async function folderListing(folder) {
  return (await regularFilesBelow(folder, '')).toSorted(compareText)
}

/**
 * The results of `read` for each of `items`, in order. The items are read in parallel, and the first failure in
 * their order is the one that rejects, so the message does not depend on timing.
 */
async function readInOrder(items, read) {
  const results = await Promise.allSettled(items.map(read))
  const failure = results.find((result) => result.status === 'rejected')
  if (failure !== undefined) {
    throw failure.reason
  }
  return results.map((result) => result.value)
}

/** The file name of a relative path. */
function fileName(path) {
  return path.slice(path.lastIndexOf('/') + 1)
}

/** Whether `excluded` (paths as EXCLUDED_LICENSE_FILES writes them) names the relative path `path`. */
function isExcluded(path, excluded) {
  return excluded.some((exclusion) =>
    exclusion.endsWith('/') ? path.startsWith(exclusion) : path === exclusion,
  )
}

/** The license files (input 3) among `paths`, the regular files of a folder in byte order. */
function licenseFilesOf(paths, licenseFile, excluded) {
  const listed = new Set(paths)
  const named = licenseFile ? [posix.normalize(licenseFile)].filter((path) => listed.has(path)) : []
  const topLevel = paths.filter((path) => !path.includes('/') && LICENSE_FILE_PATTERN.test(path))
  const licensesFolder = paths.filter((path) => /^LICENSES\/[^/]+$/.test(path))
  const nested = paths.filter(
    (path) =>
      path.includes('/') &&
      LICENSE_FILE_PATTERN.test(fileName(path)) &&
      !SOURCE_FILE_PATTERN.test(path),
  )
  return [...new Set([...named, ...topLevel, ...licensesFolder, ...nested])].filter(
    (path) => !isExcluded(path, excluded),
  )
}

/** The prebuilt libraries (input 8) among `paths`, the regular files of a folder in byte order. */
function prebuiltLibrariesOf(paths) {
  return paths.filter(
    (path) =>
      PREBUILT_LIBRARY_PATTERN.test(path) && !path.split('/').slice(0, -1).includes('tests'),
  )
}

/**
 * The paths of the license files of a package folder (input 3), relative to it with `/`, in order, without the
 * paths `excluded` names (written as the `path` of EXCLUDED_LICENSE_FILES).
 */
export async function licenseFiles(folder, licenseFile, excluded = []) {
  return licenseFilesOf(await folderListing(folder), licenseFile, excluded)
}

/** The prebuilt libraries of a package folder (input 8), relative to it with `/`, in byte order. */
export async function prebuiltLibraries(folder) {
  return prebuiltLibrariesOf(await folderListing(folder))
}

/** The workspace package named `name` in parsed `cargo metadata` output. */
function workspacePackage(metadata, name) {
  const found = metadata.packages.find((listed) => listed.source === null && listed.name === name)
  if (found === undefined) {
    throw new Error(
      `cargo metadata lists no workspace crate ${name} (docs/spec/delivery.md section 2.9).`,
    )
  }
  return found
}

/**
 * The external crates that `rootName` builds in one parsed `cargo metadata` output (input 1), each once as
 * `{ name, version, license, licenseFile, folder, repository }`, sorted by name and then by version precedence.
 */
export function artifactCrates(metadata, rootName) {
  const rootPackage = workspacePackage(metadata, rootName)
  const packagesById = new Map(metadata.packages.map((listed) => [listed.id, listed]))
  const nodesById = new Map(metadata.resolve.nodes.map((node) => [node.id, node]))
  const reached = new Set([rootPackage.id])
  const pending = [rootPackage.id]
  while (pending.length > 0) {
    for (const dependency of nodesById.get(pending.pop())?.deps ?? []) {
      // Normal (kind null) and build dependencies are built into the artifact; dev-dependencies are not.
      const built = dependency.dep_kinds.some(({ kind }) => kind === null || kind === 'build')
      if (built && !reached.has(dependency.pkg)) {
        reached.add(dependency.pkg)
        pending.push(dependency.pkg)
      }
    }
  }
  return [...reached]
    .map((id) => packagesById.get(id))
    .filter((listed) => listed.source !== null)
    .map((listed) => ({
      name: listed.name,
      version: listed.version,
      license: listed.license,
      licenseFile: listed.license_file,
      folder: dirname(listed.manifest_path),
      repository: rootPackage.repository,
    }))
    .toSorted(compareNameAndVersion)
}

/** The texts of `texts` with each distinct text once, in order of first appearance, without empty ones. */
function distinctTexts(texts) {
  return [...new Set(texts)].filter((text) => text !== '')
}

/** The entry `{ name, version, license, url, platforms, textSource, texts }` of renderNotices, with defaults. */
function noticesEntry({
  name,
  version = null,
  license = null,
  url,
  platforms = null,
  textSource = 'shipped',
  texts,
}) {
  return { name, version, license, url, platforms, textSource, texts }
}

/** The entry line of `listed` (layout of section 2.9), numbering its texts with `numberOf`. */
function entryLine(listed, numberOf) {
  const parts = [listed.version ? `${listed.name} ${listed.version}` : listed.name]
  parts.push(listed.license ?? 'see texts', listed.url)
  if (listed.platforms && listed.platforms.length < EVERY_PLATFORM.length) {
    const platforms = EVERY_PLATFORM.filter((platform) => listed.platforms.includes(platform))
    parts.push(`only ${platforms.join(' and ')}`)
  }
  if (listed.textSource === 'standard') {
    parts.push('standard text')
  }
  if (listed.textSource === 'repository') {
    parts.push('text from its repository')
  }
  parts.push(`texts ${listed.texts.map((text) => `[${numberOf(text)}]`).join(' ')}`)
  return parts.join(', ')
}

/** The text of one notices file from its parts, in the layout below, with no input or output. */
export function renderNotices(notices) {
  const { heading, scope, partsmith, occt, fonts, crates, packages, libraries } = notices
  // Texts are numbered in the order the file first refers to them, reading from the top.
  const numbers = new Map()
  const numberOf = (text) => {
    if (!numbers.has(text)) {
      numbers.set(text, numbers.size + 1)
    }
    return numbers.get(text)
  }
  const lines = (entries) => entries.map((listed) => entryLine(listed, numberOf)).join('\n')
  const blocks = [
    heading,
    GENERATED_LINE,
    `Partsmith is licensed under the Apache License 2.0, text [${numberOf(partsmith)}]. Models you make with Partsmith belong to you. ${scope} also contains the software listed below, each part under its own license; the license texts follow the list.`,
    '== Open CASCADE Technology ==',
    occt.statement,
    lines(occt.entries),
    '== Fonts ==',
    lines(fonts),
    '== Rust crates ==',
    CRATES_SOURCE_LINE,
    lines(crates),
    '== npm packages ==',
    lines(packages),
    '== Other libraries ==',
    lines(libraries),
    '== License texts ==',
  ]
  const texts = [...numbers].map(([text, number]) => `[${number}]\n\n${text.replace(/\n$/, '')}`)
  return `${[...blocks, ...texts].join('\n\n')}\n`
}

/** The value that the pattern's first group captures in the pin file `file` of `root`. */
async function pinned(root, file, pattern, name) {
  const match = pattern.exec(await readFile(join(root, file), 'utf8'))
  if (match === null) {
    throw new Error(`${file} does not set ${name} (docs/spec/delivery.md section 2.9).`)
  }
  return match[1]
}

/** The pins the notices name: OCCT's version and tag, the Emscripten SDK version and the Rust channel. */
async function readPins(root) {
  return {
    occtVersion: await pinned(
      root,
      'scripts/occt-version.sh',
      /^OCCT_VERSION=(\S+)$/m,
      'OCCT_VERSION',
    ),
    occtTag: await pinned(root, 'scripts/occt-version.sh', /^OCCT_TAG=(\S+)$/m, 'OCCT_TAG'),
    emsdkVersion: await pinned(
      root,
      'scripts/emsdk-version.sh',
      /^EMSDK_VERSION=(\S+)$/m,
      'EMSDK_VERSION',
    ),
    rustChannel: await pinned(root, 'rust-toolchain.toml', /^channel\s*=\s*"([^"]+)"/m, 'channel'),
  }
}

/** The entries of OCCT and of the code from other projects that it includes (input 4). */
async function occtEntries(root, { occtVersion, occtTag }) {
  const folder = `occt-${occtVersion}`
  const texts = [
    await normalizedCopy(root, `${folder}/LICENSE_LGPL_21.txt`),
    await normalizedCopy(root, `${folder}/OCCT_LGPL_EXCEPTION.txt`),
  ]
  const occt = noticesEntry({
    name: 'Open CASCADE Technology',
    version: occtVersion,
    license: OCCT_LICENSE,
    url: `https://github.com/Open-Cascade-SAS/OCCT/tree/${occtTag}`,
    texts,
  })
  const notices = JSON.parse(await committedCopy(root, `${folder}/bundled.json`))
  const bundledTexts = await readInOrder(notices, (notice) =>
    normalizedCopy(root, `${folder}/${notice.text}`),
  )
  const bundled = notices.map((notice, i) =>
    noticesEntry({
      name: notice.name,
      license: notice.license,
      url: `https://github.com/Open-Cascade-SAS/OCCT/blob/${occtTag}/${notice.path}`,
      texts: [bundledTexts[i]],
    }),
  )
  return [occt, ...bundled]
}

